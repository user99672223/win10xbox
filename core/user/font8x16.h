// The 16 rows drawn for UTF-16 code unit `ch` (a glyph index with ETO_GLYPH_INDEX is the same code).
inline const std::uint8_t* GlyphRows(char32_t ch) {
    if (ch >= kFirstGlyph && ch <= kLastGlyph) return kGlyphs[ch - kFirstGlyph];
    if (ch == 0xa0) return kGlyphs[0];
    return kBox;
}

// Pixel (x, y) of a glyph cell: x 0..7 from the left, y 0..15 from the top.
inline bool GlyphPixel(const std::uint8_t* rows, int x, int y) { return (rows[y] >> (7 - x)) & 1; }

