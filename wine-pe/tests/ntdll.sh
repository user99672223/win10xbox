#!/usr/bin/env bash
# Wine's ntdll conformance tests (wine-src/dlls/ntdll/tests) as one PE x64 test
# program, ntdll_test.exe, built the way Wine's own harness does it: every
# source in the directory linked into one executable with a generated
# testlist.c, one process per unit (`ntdll_test.exe <unit>`).
#
#   wine-pe/tests/ntdll.sh build [--out DIR]
#
# Compiles with llvm-mingw against Wine's own headers (the Wine sources are never
# copied into this repository; wine-pe/fetch-wine.sh fetches them). A source that
# does not compile is left out of the testlist and reported; testdll.c is a helper
# DLL embedded as a resource by Wine's build, not a unit.
# Output (default wine-pe/tests/out):
#   DIR/ntdll_test.exe     the guest
#   DIR/ntdll_test.units   the unit names in it, one per line
# Running it is tests/winetest/run_ntdll.cmake (ctest integration.winetest_ntdll,
# on the Windows jobs of ci.yml), against wine-pe/tests/ntdll.allowlist.
#
# Works from Git Bash on a Windows runner (llvm-mingw's Windows build) as well as
# on Linux.
#
# Environment: LLVM_MINGW (default /opt/llvm-mingw), WINE_SRC (default
# wine-pe/wine-src), WINE_GEN_INCLUDE (default wine-pe/build/include, optional).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
WINE_SRC="${WINE_SRC:-$ROOT/wine-pe/wine-src}"
WINE_GEN_INCLUDE="${WINE_GEN_INCLUDE:-$ROOT/wine-pe/build/include}"
TESTS="$WINE_SRC/dlls/ntdll/tests"

usage() { sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d' | sed 's/^# \{0,1\}//'; }

# ------------------------------------------------------------------- build
cmd_build() {
    local out="$HERE/out"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --out) out="${2:?}"; shift 2 ;;
            *) echo "ntdll.sh build: unknown argument '$1'" >&2; exit 2 ;;
        esac
    done
    local llvm="${LLVM_MINGW:-/opt/llvm-mingw}"
    [[ -d "$llvm/bin" ]] && export PATH="$llvm/bin:$PATH"
    local cc=x86_64-w64-mingw32-clang
    command -v "$cc" >/dev/null || { echo "ntdll.sh: $cc not found (set LLVM_MINGW)" >&2; exit 1; }
    [[ -f "$TESTS/Makefile.in" ]] || { echo "ntdll.sh: $TESTS missing (run wine-pe/fetch-wine.sh)" >&2; exit 1; }

    local obj="$out/obj"
    mkdir -p "$obj"
    local resdir; resdir="$("$cc" -print-resource-dir | tr -d '\r')"
    # As tests/wine-tests/CMakeLists.txt: Wine's headers replace the toolchain's, -w because these are Wine's sources.
    local cflags=(-std=gnu17 -g -O1 -w -nostdinc -isystem "$resdir/include"
                  -D__WINESRC__ -D_NTSYSTEM_ -DWINE_NO_LONG_TYPES -D_UCRT
                  -I "$WINE_SRC/include")
    [[ -f "$WINE_GEN_INCLUDE/unknwn.h" ]] && cflags+=(-I "$WINE_GEN_INCLUDE")
    cflags+=(-I "$WINE_SRC/include/msvcrt")

    # The sources Wine's Makefile.in lists (C files only; testdll is a helper DLL, not a unit).
    local srcs=() s
    for s in $(sed -n '/^SOURCES/,/^$/p' "$TESTS/Makefile.in" | tr -d '\\\r' | tr ' \t' '\n\n' | grep '\.c$'); do
        [[ "$s" == testdll.c ]] || srcs+=("$s")
    done

    local objs=() units=() failed=() u o
    for s in "${srcs[@]}"; do
        o="$obj/${s%.c}.o"
        if [[ ! -f "$o" || "$TESTS/$s" -nt "$o" || "${BASH_SOURCE[0]}" -nt "$o" ]]; then
            if ! "$cc" "${cflags[@]}" -c "$TESTS/$s" -o "$o" 2>"$obj/${s%.c}.err"; then
                rm -f "$o"; failed+=("$s"); continue
            fi
        fi
        objs+=("$o")
        # START_TEST(<unit>) may appear once per architecture (unwind.c): the unit name, once.
        u="$(sed -n 's/^START_TEST(\([A-Za-z0-9_]*\)).*/\1/p' "$TESTS/$s" | head -n 1 | tr -d '\r')"
        [[ -n "$u" ]] && units+=("$u")
    done
    "$cc" "${cflags[@]}" -c "$ROOT/tests/wine-tests/wine_support.c" -o "$obj/wine_support.o"

    {
        echo "/* generated by wine-pe/tests/ntdll.sh */"
        echo "#define WIN32_LEAN_AND_MEAN"
        echo "#include <windows.h>"
        echo "#define STANDALONE"
        echo "#include \"wine/test.h\""
        for u in "${units[@]}"; do echo "extern void func_$u(void);"; done
        echo "const struct test winetest_testlist[] = {"
        for u in "${units[@]}"; do echo "    { \"$u\", func_$u },"; done
        echo "    { 0, 0 }"
        echo "};"
    } > "$obj/testlist.c"
    "$cc" "${cflags[@]}" -c "$obj/testlist.c" -o "$obj/testlist.o"
    "$cc" -o "$out/ntdll_test.exe" "${objs[@]}" "$obj/testlist.o" "$obj/wine_support.o" \
        -lntdll -luser32 -ladvapi32 -lkernel32 2>"$obj/link.err" || {
        cat "$obj/link.err" >&2; echo "ntdll.sh: link failed" >&2; exit 1; }
    printf '%s\n' "${units[@]}" > "$out/ntdll_test.units"
    echo "ntdll.sh: built $out/ntdll_test.exe with ${#units[@]} units: ${units[*]}"
    if [[ ${#failed[@]} -gt 0 ]]; then
        echo "ntdll.sh: not compiled (left out of the testlist): ${failed[*]}"
        for s in "${failed[@]}"; do head -n 5 "$obj/${s%.c}.err" | sed 's/^/  /'; done
    fi
}

case "${1:-}" in
    build) shift; cmd_build "$@" ;;
    -h|--help|"") usage ;;
    *) echo "ntdll.sh: unknown command '$1'" >&2; usage >&2; exit 2 ;;
esac
