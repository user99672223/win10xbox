#!/usr/bin/env bash
# Wine's ntdll conformance tests (wine-src/dlls/ntdll/tests) as one PE x64 test
# program, ntdll_test.exe, built and run the way Wine's own harness does it:
# every source in the directory linked into one executable with a generated
# testlist.c, one process per unit (`ntdll_test.exe <unit>`).
#
#   wine-pe/tests/ntdll.sh build [--out DIR]
#   wine-pe/tests/ntdll.sh run --host <win10xbox.exe> --machine <dir> [--emulator <wine>]
#                              [--exe <ntdll_test.exe>] [--baseline FILE] [--results DIR]
#                              [--timeout SECONDS] [--units "rtl path ..."]
#
# build: compiles with llvm-mingw against Wine's own headers (the Wine sources
#   are never copied into this repository; wine-pe/fetch-wine.sh fetches them).
#   A source that does not compile is left out of the testlist and reported;
#   testdll.c is a helper DLL embedded as a resource by Wine's build, not a unit.
#   Output: DIR/ntdll_test.exe (default wine-pe/tests/out).
# run: copies the exe to <machine>/guest-wine/ntdll_test.exe and runs each unit
#   as `win10xbox --machine <dir> C:\guest-wine\ntdll_test.exe <unit>`. Wine's
#   test.h ends a unit with "<unit>: N tests executed (T marked as todo, F as
#   flaky, K failures), S skipped."; a unit without that line crashed (or timed
#   out) and counts as 0 executed. Against the baseline (lines "<unit> <max
#   failures>"), a unit fails the run when it executed nothing or has more
#   failures than recorded; fewer prints IMPROVED. Prints a Markdown table of
#   unit / executed / failed / skipped (docs/WINETEST.md) and exits 1 on any
#   regression.
#
# Environment: LLVM_MINGW (default /opt/llvm-mingw), WINE_SRC (default
# wine-pe/wine-src), WINE_GEN_INCLUDE (default wine-pe/build/include, optional).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
WINE_SRC="${WINE_SRC:-$ROOT/wine-pe/wine-src}"
WINE_GEN_INCLUDE="${WINE_GEN_INCLUDE:-$ROOT/wine-pe/build/include}"
TESTS="$WINE_SRC/dlls/ntdll/tests"
DEFAULT_UNITS="rtl rtlstr string time env path large_int info file om reg"

usage() { sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d' | sed 's/^# \{0,1\}//'; }

# ------------------------------------------------------------------- build
cmd_build() {
    local out="$HERE/out"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --out) out="${2:?}"; shift 2 ;;
            *) echo "ntdll.sh build: unknown argument '$1'" >&2; exit 2 ;;
        esac
    done
    local llvm="${LLVM_MINGW:-/opt/llvm-mingw}"
    [[ -d "$llvm/bin" ]] && export PATH="$llvm/bin:$PATH"
    local cc=x86_64-w64-mingw32-clang
    command -v "$cc" >/dev/null || { echo "ntdll.sh: $cc not found (set LLVM_MINGW)" >&2; exit 1; }
    [[ -f "$TESTS/Makefile.in" ]] || { echo "ntdll.sh: $TESTS missing (run wine-pe/fetch-wine.sh)" >&2; exit 1; }

    local obj="$out/obj"
    mkdir -p "$obj"
    local resdir; resdir="$("$cc" -print-resource-dir)"
    # As tests/wine-tests/CMakeLists.txt: Wine's headers replace the toolchain's, -w because these are Wine's sources.
    local cflags=(-std=gnu17 -g -O1 -w -nostdinc -isystem "$resdir/include"
                  -D__WINESRC__ -D_NTSYSTEM_ -DWINE_NO_LONG_TYPES -D_UCRT
                  -I "$WINE_SRC/include")
    [[ -f "$WINE_GEN_INCLUDE/unknwn.h" ]] && cflags+=(-I "$WINE_GEN_INCLUDE")
    cflags+=(-I "$WINE_SRC/include/msvcrt")

    # The sources Wine's Makefile.in lists (C files only; testdll is a helper DLL, not a unit).
    local srcs=() s
    for s in $(sed -n '/^SOURCES/,/^$/p' "$TESTS/Makefile.in" | tr -d '\\' | tr ' \t' '\n\n' | grep '\.c$'); do
        [[ "$s" == testdll.c ]] || srcs+=("$s")
    done

    local objs=() units=() failed=() u o
    for s in "${srcs[@]}"; do
        o="$obj/${s%.c}.o"
        if [[ ! -f "$o" || "$TESTS/$s" -nt "$o" || "${BASH_SOURCE[0]}" -nt "$o" ]]; then
            if ! "$cc" "${cflags[@]}" -c "$TESTS/$s" -o "$o" 2>"$obj/${s%.c}.err"; then
                rm -f "$o"; failed+=("$s"); continue
            fi
        fi
        objs+=("$o")
        # START_TEST(<unit>) may appear once per architecture (unwind.c): the unit name, once.
        u="$(sed -n 's/^START_TEST(\([A-Za-z0-9_]*\)).*/\1/p' "$TESTS/$s" | head -n 1)"
        [[ -n "$u" ]] && units+=("$u")
    done
    "$cc" "${cflags[@]}" -c "$ROOT/tests/wine-tests/wine_support.c" -o "$obj/wine_support.o"

    {
        echo "/* generated by wine-pe/tests/ntdll.sh */"
        echo "#define WIN32_LEAN_AND_MEAN"
        echo "#include <windows.h>"
        echo "#define STANDALONE"
        echo "#include \"wine/test.h\""
        for u in "${units[@]}"; do echo "extern void func_$u(void);"; done
        echo "const struct test winetest_testlist[] = {"
        for u in "${units[@]}"; do echo "    { \"$u\", func_$u },"; done
        echo "    { 0, 0 }"
        echo "};"
    } > "$obj/testlist.c"
    "$cc" "${cflags[@]}" -c "$obj/testlist.c" -o "$obj/testlist.o"
    "$cc" -o "$out/ntdll_test.exe" "${objs[@]}" "$obj/testlist.o" "$obj/wine_support.o" \
        -lntdll -luser32 -ladvapi32 -lkernel32 2>"$obj/link.err" || {
        cat "$obj/link.err" >&2; echo "ntdll.sh: link failed" >&2; exit 1; }
    echo "ntdll.sh: built $out/ntdll_test.exe with ${#units[@]} units: ${units[*]}"
    if [[ ${#failed[@]} -gt 0 ]]; then
        echo "ntdll.sh: not compiled (left out of the testlist): ${failed[*]}"
        for s in "${failed[@]}"; do head -n 5 "$obj/${s%.c}.err" | sed 's/^/  /'; done
    fi
}

# --------------------------------------------------------------------- run
cmd_run() {
    local host="" machine="" emulator="" exe="$HERE/out/ntdll_test.exe" baseline="$HERE/ntdll.baseline"
    local results="" timeout=120 units="$DEFAULT_UNITS"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --host) host="${2:?}"; shift 2 ;;
            --machine) machine="${2:?}"; shift 2 ;;
            --emulator) emulator="$2"; shift 2 ;;
            --exe) exe="${2:?}"; shift 2 ;;
            --baseline) baseline="$2"; shift 2 ;;
            --results) results="${2:?}"; shift 2 ;;
            --timeout) timeout="${2:?}"; shift 2 ;;
            --units) units="${2:?}"; shift 2 ;;
            *) echo "ntdll.sh run: unknown argument '$1'" >&2; exit 2 ;;
        esac
    done
    [[ -n "$host" && -n "$machine" ]] || { echo "ntdll.sh run: --host and --machine are required" >&2; exit 2; }
    [[ -f "$exe" ]] || { echo "ntdll.sh run: $exe missing (ntdll.sh build)" >&2; exit 1; }
    [[ -f "$machine/Windows/builtin/ntdll.dll" ]] || { echo "ntdll.sh run: no Wine builtins in $machine" >&2; exit 1; }
    [[ -f "$machine/Windows/System32/c_1252.nls" ]] || { echo "ntdll.sh run: no NLS data in $machine" >&2; exit 1; }
    results="${results:-$(dirname "$exe")/results}"
    mkdir -p "$machine/guest-wine" "$results"
    cp -f "$exe" "$machine/guest-wine/ntdll_test.exe"

    local gmachine="$machine"
    if [[ -n "$emulator" ]]; then gmachine="Z:$machine"; fi   # Wine: Z: is the Unix root
    gmachine="${gmachine//\//\\}"

    local re='([0-9]+) tests executed \(([0-9]+) marked as todo, ([0-9]+) as flaky, ([0-9]+) failures?\), ([0-9]+) skipped'
    local table="| unit | outcome | executed | failed | skipped | todo | exit |"$'\n'"|---|---|---:|---:|---:|---:|---:|"
    local bad=0 u rc log line outcome executed failed skipped todo max
    for u in $units; do
        log="$results/$u.log"
        rc=0
        WIN10XBOX_DEBUG=-all timeout -k 5 "$timeout" $emulator "$host" --machine "$gmachine" \
            'C:\guest-wine\ntdll_test.exe' "$u" </dev/null >"$log" 2>&1 || rc=$?
        line="$(grep -aE "^[0-9a-f]+:$u:[^ ]* $re" "$log" | tail -n 1 || true)"
        executed=0 failed=0 skipped=0 todo=0
        if [[ "$line" =~ $re ]]; then
            outcome=ok
            executed=${BASH_REMATCH[1]} todo=${BASH_REMATCH[2]} failed=${BASH_REMATCH[4]} skipped=${BASH_REMATCH[5]}
        elif [[ $rc -eq 124 || $rc -eq 137 ]]; then
            outcome=timeout
        else
            outcome=crashed
        fi
        table+=$'\n'"| $u | $outcome | $executed | $failed | $skipped | $todo | $rc |"
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$u" "$outcome" "$executed" "$failed" "$skipped" "$todo" "$rc" > "$results/$u.tsv"

        max="$( [[ -f "$baseline" ]] && awk -v u="$u" '$1 == u { print $2 }' "$baseline" || true)"
        local verdict="ok"
        if [[ "$executed" -eq 0 ]]; then
            verdict="REGRESSION: nothing executed ($outcome; last line: $(grep -aE '\.c:[0-9]+:' "$log" | tail -n 1 | cut -c1-160))"
        elif [[ -z "$max" ]]; then
            verdict="REGRESSION: no baseline for $u in $baseline"
        elif [[ "$failed" -gt "$max" ]]; then
            verdict="REGRESSION: $failed failures, baseline allows $max"
        elif [[ "$failed" -lt "$max" ]]; then
            verdict="IMPROVED: $failed failures < baseline $max; lower it in $(basename "$baseline")"
        fi
        [[ "$verdict" == REGRESSION* ]] && bad=1
        echo "WINETEST ntdll:$u outcome=$outcome executed=$executed failed=$failed skipped=$skipped todo=$todo exit=$rc baseline=${max:-none} -> $verdict"
    done
    echo
    echo "$table"
    if [[ $bad -ne 0 ]]; then
        echo "ntdll.sh: FAIL (logs in $results)"
        exit 1
    fi
    echo "ntdll.sh: PASS (baseline holds)"
}

case "${1:-}" in
    build) shift; cmd_build "$@" ;;
    run) shift; cmd_run "$@" ;;
    -h|--help|"") usage ;;
    *) echo "ntdll.sh: unknown command '$1'" >&2; usage >&2; exit 2 ;;
esac
