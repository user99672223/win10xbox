#!/usr/bin/env bash
# Build Wine's msvcrt conformance tests (dlls/msvcrt/tests) as one PE x64
# guest and run selected units through the layer (win10xbox.exe).
#
#   wine-pe/tests/msvcrt.sh build --out <dir> [--gen-include <dir>]
#   wine-pe/tests/msvcrt.sh run   --out <dir> --host <win10xbox.exe> --machine <dir>
#                                   [--emulator <wine>] [--units "cpp data string"]
#                                   [--timeout <s>] [--baseline <file>]
#   wine-pe/tests/msvcrt.sh all   (build, then run; takes the options of both)
#
# build: compiles the msvcrt test sources of wine-pe/wine-src (fetch-wine.sh;
#   LGPL, never copied into this repository) plus a generated test list into
#   <out>/msvcrt_test.exe with llvm-mingw, linked the way Wine links a CRT-DLL test:
#   Wine's msvcrt headers with -D_MSVCR_VER=0, an import library for Wine's own
#   msvcrt.dll made from dlls/msvcrt/msvcrt.spec, and no other C runtime (the
#   mingw one would hide what msvcrt.dll does). wine-pe/tests/crt_support.c supplies
#   the startup code and __wine_dbg_strdup. No widl-generated headers are needed.
# run: copies the guest to <machine>/guest-wine/ and runs
#   `C:\guest-wine\msvcrt_test.exe <unit>` once per unit with a per-unit cap.
#   Wine's harness ends a unit with "N tests executed (T marked as todo, F as
#   flaky, K failures), S skipped."; no such line = crashed, exit 124 = timeout.
#   One line per unit goes to <out>/msvcrt.tsv and to stdout as
#   "WINETEST msvcrt:<unit> status=... executed=... failures=...".
#
# Gate (the baseline file, default wine-pe/tests/msvcrt.baseline, lines
# "<unit> <run|crash|timeout> <max_failures>"):
#   run    the unit must complete with failures <= max (fewer prints IMPROVED)
#   crash|timeout  must not complete; completing prints IMPROVED (record it)
#   and at least one assertion must have executed over all units.
# Exit: 0 baseline holds, 1 regression, 2 usage, 77 prerequisites missing
# (the Wine sources, the builtins or the NLS data): ctest SKIP.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SRC="${WINE_SRC:-$ROOT/wine-pe/wine-src}"
LLVM_MINGW="${LLVM_MINGW:-/opt/llvm-mingw}"
[[ -d "$LLVM_MINGW/bin" ]] && export PATH="$LLVM_MINGW/bin:$PATH"

MODE="${1:-}"; shift || true
OUT=""; GEN="$ROOT/wine-pe/build/include"; HOST=""; MACHINE=""; EMULATOR=""
UNITS="cpp data dir environ file heap locale misc printf scanf signal string time"; TIMEOUT=45; BASELINE="$HERE/msvcrt.baseline"
while [[ $# -gt 0 ]]; do
    case "$1" in
        --out) OUT="$2"; shift 2 ;;
        --gen-include) GEN="$2"; shift 2 ;;
        --host) HOST="$2"; shift 2 ;;
        --machine) MACHINE="$2"; shift 2 ;;
        --emulator) EMULATOR="$2"; shift 2 ;;
        --units) UNITS="$2"; shift 2 ;;
        --timeout) TIMEOUT="$2"; shift 2 ;;
        --baseline) BASELINE="$2"; shift 2 ;;
        *) echo "msvcrt.sh: unknown argument '$1'" >&2; exit 2 ;;
    esac
done
[[ -n "$OUT" ]] || { echo "msvcrt.sh: --out is required" >&2; exit 2; }
mkdir -p "$OUT"
EXE="$OUT/msvcrt_test.exe"

skip() { echo "SKIP: $*"; exit 77; }

do_build() {
    local tdir="$SRC/dlls/msvcrt/tests"
    [[ -f "$SRC/include/wine/test.h" && -d "$tdir" ]] || skip "$SRC missing (run wine-pe/fetch-wine.sh)"
    command -v x86_64-w64-mingw32-clang >/dev/null || skip "x86_64-w64-mingw32-clang not found (llvm-mingw)"
    local cc=x86_64-w64-mingw32-clang
    local res; res="$($cc -print-resource-dir)"
    # Every test source the upstream Makefile lists, so the binary is Wine's msvcrt_test.exe.
    local srcs=() names=()
    local f
    for f in $(sed -n '/^SOURCES/,/^$/p' "$tdir/Makefile.in" | tr -d '\\' | tr ' \t' '\n\n' | grep '\.c$'); do
        srcs+=("$tdir/$f"); names+=("${f%.c}")
    done
    [[ ${#srcs[@]} -gt 0 ]] || { echo "msvcrt.sh: no SOURCES in $tdir/Makefile.in" >&2; exit 1; }
    local tl="$OUT/msvcrt_testlist.c"
    {
        echo "/* generated by wine-pe/tests/msvcrt.sh */"
        echo "#define WIN32_LEAN_AND_MEAN"
        echo "#include <windows.h>"
        echo "#define STANDALONE"
        echo "#include \"wine/test.h\""
        for n in "${names[@]}"; do echo "extern void func_$n(void);"; done
        echo "const struct test winetest_testlist[] = {"
        for n in "${names[@]}"; do echo "    { \"$n\", func_$n },"; done
        echo "    { 0, 0 }"
        echo "};"
    } > "$tl"
    # Flags as Wine builds a CRT-DLL test (dlls/msvcrt/tests/Makefile.in: TESTDLL = msvcrt.dll,
    # IMPORTS = advapi32): Wine's own msvcrt headers (-I include/msvcrt, -D_MSVCR_VER=0 as makedep.c gives a msvcrt.dll test) and no C
    # runtime but msvcrt.dll itself, so the suite exercises the builtin msvcrt.dll the layer
    # loads. crt_support.c supplies __wine_dbg_strdup and the msvcrt-only startup code.
    local flags=(-std=gnu17 -O1 -g0 -w -nostdinc -isystem "$res/include"
        -I"$SRC/include" -I"$GEN" -I"$SRC/include/msvcrt"
        -D__WINESRC__ -D_NTSYSTEM_ -DWINE_NO_LONG_TYPES -D_MSVCR_VER=0)
    local rt; rt="$($cc -print-libgcc-file-name)"
    # Import library of Wine's msvcrt.dll, made from its export spec (what Wine's own build does).
    # llvm-mingw's libmsvcrt.a lacks the stdio family (printf, sscanf, _filbuf ...), which its
    # headers provide as inline code instead of imports.
    local spec="$SRC/dlls/msvcrt/msvcrt.spec" def="$OUT/msvcrt_wine.def"
    [[ -f "$spec" ]] || skip "$spec missing (run wine-pe/fetch-wine.sh)"
    awk 'BEGIN { print "LIBRARY msvcrt.dll"; print "EXPORTS" }
        /^@ / {
            type = $2; i = 3; keep = 1
            while ($i ~ /^-/) {
                if ($i ~ /^-arch=/) {
                    a = substr($i, 7); keep = 0
                    n = split(a, parts, ",")
                    for (k = 1; k <= n; k++) if (parts[k] == "win64" || parts[k] == "x86_64" || parts[k] ~ /^!/) keep = 1
                }
                i++
            }
            name = $i; sub(/\(.*/, "", name)
            if (!keep || name == "") next
            if (type == "extern") print name " DATA"; else print name
        }' "$spec" > "$def"
    llvm-dlltool -m i386:x86-64 -d "$def" -l "$OUT/libmsvcrt_wine.a" \
        || { echo "msvcrt.sh: llvm-dlltool failed" >&2; exit 1; }
    echo "msvcrt.sh: compiling ${#srcs[@]} test sources (${names[*]})"
    "$cc" "${flags[@]}" -DWIN10XBOX_CRT_MSVCRT -nostdlib -nostartfiles -Wl,--entry,mainCRTStartup \
        -Wl,--subsystem,console "${srcs[@]}" "$tl" "$HERE/crt_support.c" -o "$EXE" \
        "$OUT/libmsvcrt_wine.a" -ladvapi32 -luser32 -lkernel32 -lntdll "$rt" \
        || { echo "msvcrt.sh: build failed" >&2; exit 1; }
    echo "msvcrt.sh: built $EXE"
}

baseline_of() {   # <unit> -> "<expect> <max>"
    [[ -f "$BASELINE" ]] || { echo "run 999999"; return; }
    awk -v u="$1" '$1 == u { print $2, $3; found = 1 } END { if (!found) print "run 999999" }' "$BASELINE"
}

do_run() {
    [[ -n "$HOST" && -n "$MACHINE" ]] || { echo "msvcrt.sh: run needs --host and --machine" >&2; exit 2; }
    [[ -f "$EXE" ]] || skip "$EXE missing (build step skipped or failed)"
    [[ -f "$MACHINE/Windows/builtin/ntdll.dll" ]] || skip "$MACHINE/Windows/builtin/ntdll.dll missing (Wine PE builtins)"
    [[ -f "$MACHINE/Windows/System32/c_1252.nls" ]] || skip "$MACHINE/Windows/System32/c_1252.nls missing (NLS data)"
    mkdir -p "$MACHINE/guest-wine"
    cp -f "$EXE" "$MACHINE/guest-wine/msvcrt_test.exe"
    local wmachine="$MACHINE"
    if [[ -n "$EMULATOR" && "$wmachine" == /* ]]; then wmachine="Z:$wmachine"; fi
    wmachine="${wmachine//\//\\}"
    export WIN10XBOX_DEBUG="${WIN10XBOX_DEBUG_SPEC:--all}"
    local tsv="$OUT/msvcrt.tsv" total=0 bad=0
    : > "$tsv"
    local re='([0-9]+) tests executed \(([0-9]+) marked as todo, ([0-9]+) as flaky, ([0-9]+) failures?\), ([0-9]+) skipped'
    local unit
    for unit in $UNITS; do
        local log="$OUT/msvcrt_$unit.log" t0 rc status=crashed ex=0 todo=0 fl=0 fails=0 sk=0 last=""
        t0=$(date +%s)
        timeout -k 5 "$TIMEOUT" $EMULATOR "$HOST" --machine "$wmachine" 'C:\guest-wine\msvcrt_test.exe' "$unit" \
            < /dev/null > "$log" 2>&1
        rc=$?
        local secs=$(( $(date +%s) - t0 ))
        # Units that spawn the test exe again (file, dir) print a summary per process; the
        # parent's is the one whose process id prefixes the first line of the log.
        local pid0; pid0="$(grep -aoE '^[0-9a-f]+:' "$log" | head -1)"
        local summary; summary="$(grep -aE "^${pid0:-[0-9a-f]+:}$unit:.*$re" "$log" | tail -1)"
        [[ -z "$summary" ]] && summary="$(grep -aE "^[0-9a-f]+:$unit:.*$re" "$log" | tail -1)"
        [[ -z "$summary" ]] && summary="$(grep -aE "$re" "$log" | tail -1)"
        if [[ $rc -eq 124 || $rc -eq 137 ]]; then
            status=timeout
        elif [[ -n "$summary" && "$summary" =~ $re ]]; then
            status=ok; ex=${BASH_REMATCH[1]}; todo=${BASH_REMATCH[2]}; fl=${BASH_REMATCH[3]}
            fails=${BASH_REMATCH[4]}; sk=${BASH_REMATCH[5]}
        fi
        if [[ $status != ok ]]; then
            last="$(grep -aoE '[A-Za-z0-9_]+\.c:[0-9]+:[^\r]*' "$log" | tail -1 | cut -c1-160)"
        fi
        # Executed counts survive a crash: Wine prints them only at the end, so a
        # crashed unit contributes 0 to the total.
        total=$(( total + ex ))
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$unit" "$status" "$ex" "$todo" "$fl" "$fails" "$sk" \
            "$rc" "$secs" "$last" >> "$tsv"
        echo "WINETEST msvcrt:$unit status=$status executed=$ex todo=$todo flaky=$fl failures=$fails skipped=$sk exit=$rc time=${secs}s"
        [[ -n "$last" ]] && echo "  last test line: $last"
        grep -a 'Test failed' "$log" | head -5 | cut -c1-200 | sed 's/^/  /'
        if [[ $status != ok ]]; then   # how it ended: the last lines of the log
            tail -n 8 "$log" | tr -d '\r' | cut -c1-200 | sed 's/^/  | /'
        fi
        grep -a '^win10xbox: ' "$log" | head -3 | sed 's/^/  /'
        read -r expect max <<<"$(baseline_of "$unit")"
        if [[ $expect == run ]]; then
            if [[ $status != ok ]]; then
                echo "  REGRESSION: baseline is 'completes', now $status"; bad=1
            elif (( fails > max )); then
                echo "  REGRESSION: $fails failures, baseline allows $max"; bad=1
            elif (( fails < max )); then
                echo "  IMPROVED: $fails failures < baseline $max; lower $BASELINE"
            fi
        elif [[ $status == ok ]]; then
            echo "  IMPROVED: now completes ($ex executed, $fails failures), baseline is '$expect'; update $BASELINE"
        else
            echo "  XFAIL: $status as recorded"
        fi
    done
    echo "WINETEST msvcrt total executed=$total"
    if (( total < 1 )); then echo "FAIL: no assertion executed in any unit"; exit 1; fi
    (( bad == 0 )) || { echo "FAIL: msvcrt conformance below baseline (logs in $OUT)"; exit 1; }
    echo "PASS (baseline holds)"
}

case "$MODE" in
    build) do_build ;;
    run) do_run ;;
    all) do_build; do_run ;;
    *) sed -n '2,/^set -uo/p' "${BASH_SOURCE[0]}" | sed '$d' | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
