#!/usr/bin/env bash
# Build one Wine conformance-test directory (dlls/<dll>/tests, LGPL, compiled
# from wine-pe/wine-src and never copied into this repository) as a single
# x86_64 PE, <dll>_test.exe, the way Wine's own build does: every unit
# (START_TEST(<unit>) in a .c file of SOURCES) is linked into one binary with a
# generated test list, and `<dll>_test.exe <unit>` runs one unit.
#
#   wine-pe/tests/build_winetest.sh <dll> <out-dir>
#
# Writes <out-dir>/<dll>_test.exe and <out-dir>/<dll>_test.units (one unit name
# per line, in SOURCES order). Exit status: 0 on success, 1 on a build error.
#
# Environment:
#   LLVM_MINGW        llvm-mingw root (default /opt/llvm-mingw)
#   WINE_SRC          Wine sources (default wine-pe/wine-src, wine-pe/fetch-wine.sh)
#   WINE_GEN_INCLUDE  widl-generated headers (default wine-pe/build/include, made
#                     by wine-pe/build.sh); added to the include path when present
#   SUPPORT_C         extra C file linked in (default tests/wine-tests/wine_support.c:
#                     __wine_dbg_strdup, which llvm-mingw's ntdll import lib lacks)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
dll="${1:?usage: build_winetest.sh <dll> <out-dir>}"
out="${2:?usage: build_winetest.sh <dll> <out-dir>}"
LLVM_MINGW="${LLVM_MINGW:-/opt/llvm-mingw}"
WINE_SRC="${WINE_SRC:-$ROOT/wine-pe/wine-src}"
WINE_GEN_INCLUDE="${WINE_GEN_INCLUDE:-$ROOT/wine-pe/build/include}"
SUPPORT_C="${SUPPORT_C:-$ROOT/tests/wine-tests/wine_support.c}"
[[ -d "$LLVM_MINGW/bin" ]] && export PATH="$LLVM_MINGW/bin:$PATH"
CC=x86_64-w64-mingw32-clang
RC=x86_64-w64-mingw32-windres

tdir="$WINE_SRC/dlls/$dll/tests"
mk="$tdir/Makefile.in"
[[ -f "$mk" ]] || { echo "build_winetest: $mk missing (run wine-pe/fetch-wine.sh)" >&2; exit 1; }

# Makefile.in variables, with "\" continuation lines joined.
mkvar() {
    sed -e ':a' -e '/\\$/N; s/\\\n//; ta' "$mk" | sed -n "s/^[[:space:]]*$1[[:space:]]*=//p" | head -n 1
}
sources=($(mkvar SOURCES))
imports=($(mkvar IMPORTS))

resdir="$("$CC" -print-resource-dir)"
inc=(-I"$tdir" -I"$WINE_SRC/include")
[[ -f "$WINE_GEN_INCLUDE/unknwn.h" ]] && inc+=(-I"$WINE_GEN_INCLUDE")
inc+=(-I"$WINE_SRC/include/msvcrt")
defs=(-D__WINESRC__ -D_NTSYSTEM_ -DWINE_NO_LONG_TYPES -D_UCRT)

obj="$out/obj-$dll"
mkdir -p "$out" "$obj"
rm -f "$obj"/*.o
units=()
for s in "${sources[@]}"; do
    case "$s" in
        *.c)
            u="$(sed -n 's/^START_TEST(\([A-Za-z0-9_]*\)).*/\1/p' "$tdir/$s" | head -n 1)"
            [[ -n "$u" ]] && units+=("$u")
            "$CC" -c -O1 -g0 -w -std=gnu17 -nostdinc -isystem "$resdir/include" "${inc[@]}" "${defs[@]}" \
                -o "$obj/${s%.c}.o" "$tdir/$s" ;;
        *.rc)
            "$RC" "${inc[@]}" "${defs[@]}" -i "$tdir/$s" -o "$obj/${s%.rc}.res.o" ;;
        *) echo "build_winetest: $dll: ignoring source $s" >&2 ;;
    esac
done

# The test list (Wine's make_ctests equivalent); STANDALONE gives test.h's main().
tl="$obj/testlist.c"
{
    echo "/* generated by wine-pe/tests/build_winetest.sh */"
    echo "#define WIN32_LEAN_AND_MEAN"
    echo "#include <windows.h>"
    echo "#define STANDALONE"
    echo "#include \"wine/test.h\""
    for u in "${units[@]}"; do echo "extern void func_$u(void);"; done
    echo "const struct test winetest_testlist[] = {"
    for u in "${units[@]}"; do echo "    { \"$u\", func_$u },"; done
    echo "    { 0, 0 }"
    echo "};"
} > "$tl"
"$CC" -c -O1 -g0 -w -std=gnu17 -nostdinc -isystem "$resdir/include" "${inc[@]}" "${defs[@]}" -o "$obj/testlist.o" "$tl"
"$CC" -c -O1 -g0 -w -o "$obj/support.o" "$SUPPORT_C"

libs=()
for i in "${imports[@]}"; do libs+=("-l$i"); done
libs+=(-lole32 -loleaut32 -luser32 -lgdi32 -ladvapi32 -lshell32 -lshlwapi -luuid -lversion -lkernel32 -lntdll)
"$CC" -o "$out/${dll}_test.exe" "$obj"/*.o "${libs[@]}"
printf '%s\n' "${units[@]}" > "$out/${dll}_test.units"
echo "build_winetest: $out/${dll}_test.exe (${#units[@]} units: ${units[*]})"
