#!/usr/bin/env bash
# Build Wine's conformance tests for one imaging/text DLL (dlls/<dll>/tests, <dll> in
# propsys windowscodecs mlang gdiplus dwrite) as one PE x64 guest and run its units
# through the layer (win10xbox.exe). Generic over the dll: exe <dll>_test.exe, units
# from SOURCES of the suite's Makefile.in, link libraries from its IMPORTS (plus the
# standard set), default baseline wine-pe/tests/<dll>.baseline.
#
#   wine-pe/tests/media.sh build --dll <dll> --out <dir> [--gen-include <dir>]
#   wine-pe/tests/media.sh run   --dll <dll> --out <dir> --host <win10xbox.exe> --machine <dir>
#                                   [--emulator <wine>] [--units "bmpformat info"]
#                                   [--timeout <s>] [--baseline <file>]
#   wine-pe/tests/media.sh all   --dll <dll> (build, then run; takes the options of both)
#
# build: compiles the <dll> test sources of wine-pe/wine-src (fetch-wine.sh;
#   LGPL, never copied into this repository) plus a generated test list into
#   <out>/${DLL}_test.exe with llvm-mingw, the same way tests/wine-tests does
#   (Wine's headers, STANDALONE test.h). Needs Wine's widl-generated headers
#   (wine-pe/build/include, made by wine-pe/build.sh or the wine-pe-include CI
#   artifact) because the tests include them. A suite resource.rc is
#   compiled with windres (its .ttf fonts ship with the sources) and linked in.
# run: copies the guest to <machine>/guest-wine/ and runs
#   `C:\guest-wine\<dll>_test.exe <unit>` once per unit with a per-unit cap.
#   Wine's harness ends a unit with "N tests executed (T marked as todo, F as
#   flaky, K failures), S skipped."; no such line = crashed, exit 124 = timeout.
#   One line per unit goes to <out>/${DLL}.tsv and to stdout as
#   "WINETEST $DLL:<unit> status=... executed=... failures=...".
#
# Gate (the baseline file, default wine-pe/tests/<dll>.baseline, lines
# "<unit> <run|crash|timeout> <max_failures>"):
#   run    the unit must complete with failures <= max (fewer prints IMPROVED)
#   crash|timeout  must not complete; completing prints IMPROVED (record it)
#   and at least one assertion must have executed over all units (unless the baseline records no "run" unit).
# Exit: 0 baseline holds, 1 regression, 2 usage, 77 prerequisites missing
# (the Wine sources, the builtins or the NLS data): ctest SKIP.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SRC="${WINE_SRC:-$ROOT/wine-pe/wine-src}"
LLVM_MINGW="${LLVM_MINGW:-/opt/llvm-mingw}"
[[ -d "$LLVM_MINGW/bin" ]] && export PATH="$LLVM_MINGW/bin:$PATH"

MODE="${1:-}"; shift || true
OUT=""; GEN="$ROOT/wine-pe/build/include"; HOST=""; MACHINE=""; EMULATOR=""
DLL=""; UNITS=""; TIMEOUT=30; BASELINE=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --dll) DLL="$2"; shift 2 ;;
        --out) OUT="$2"; shift 2 ;;
        --gen-include) GEN="$2"; shift 2 ;;
        --host) HOST="$2"; shift 2 ;;
        --machine) MACHINE="$2"; shift 2 ;;
        --emulator) EMULATOR="$2"; shift 2 ;;
        --units) UNITS="$2"; shift 2 ;;
        --timeout) TIMEOUT="$2"; shift 2 ;;
        --baseline) BASELINE="$2"; shift 2 ;;
        *) echo "media.sh: unknown argument '$1'" >&2; exit 2 ;;
    esac
done
case "$DLL" in propsys|windowscodecs|mlang|gdiplus|dwrite) ;; *) echo "media.sh: --dll must be one of propsys windowscodecs mlang gdiplus dwrite" >&2; exit 2 ;; esac
[[ -n "$BASELINE" ]] || BASELINE="$HERE/$DLL.baseline"
[[ -n "$OUT" ]] || { echo "media.sh: --out is required" >&2; exit 2; }
mkdir -p "$OUT"
EXE="$OUT/${DLL}_test.exe"

skip() { echo "SKIP: $*"; exit 77; }

do_build() {
    local tdir="$SRC/dlls/$DLL/tests"
    [[ -f "$SRC/include/wine/test.h" && -d "$tdir" ]] || skip "$SRC missing (run wine-pe/fetch-wine.sh)"
    [[ -f "$GEN/unknwn.h" ]] || skip "$GEN/unknwn.h missing (Wine's generated headers: wine-pe/build.sh or the wine-pe-include artifact)"
    command -v x86_64-w64-mingw32-clang >/dev/null || skip "x86_64-w64-mingw32-clang not found (llvm-mingw)"
    local cc=x86_64-w64-mingw32-clang
    local res; res="$($cc -print-resource-dir)"
    # Every test source the upstream Makefile lists, so the binary is Wine's ${DLL}_test.exe.
    local srcs=() names=()
    local f
    for f in $(sed -n '/^SOURCES/,/^$/p' "$tdir/Makefile.in" | tr -d '\\' | tr ' \t' '\n\n' | grep '\.c$'); do
        srcs+=("$tdir/$f"); names+=("${f%.c}")
    done
    [[ ${#srcs[@]} -gt 0 ]] || { echo "media.sh: no SOURCES in $tdir/Makefile.in" >&2; exit 1; }
    local tl="$OUT/${DLL}_testlist.c"
    {
        echo "/* generated by wine-pe/tests/media.sh */"
        echo "#define WIN32_LEAN_AND_MEAN"
        echo "#include <windows.h>"
        echo "#define STANDALONE"
        echo "#include \"wine/test.h\""
        for n in "${names[@]}"; do echo "extern void func_$n(void);"; done
        echo "const struct test winetest_testlist[] = {"
        for n in "${names[@]}"; do echo "    { \"$n\", func_$n },"; done
        echo "    { 0, 0 }"
        echo "};"
    } > "$tl"
    local flags=(-std=gnu17 -O1 -g0 -w -nostdinc -isystem "$res/include"
        -I"$SRC/include" -I"$GEN" -I"$SRC/include/msvcrt"
        -D__WINESRC__ -D_NTSYSTEM_ -DWINE_NO_LONG_TYPES -D_UCRT)
    # dwrite's layout.c calls the two-argument wcstok (Wine builds it with this macro).
    [[ $DLL == dwrite ]] && flags+=(-D_CRT_NON_CONFORMING_WCSTOK)
    # Link libraries: the suite's Makefile.in IMPORTS mapped to -l<lib>, then the standard set.
    local libs=() l
    for l in $(sed -n 's/^IMPORTS[[:space:]]*=//p' "$tdir/Makefile.in") ntdll kernel32 user32 advapi32 gdi32 \
            shell32 ole32 oleaut32 version ws2_32 shlwapi uuid winmm secur32 rpcrt4 crypt32; do
        [[ " ${libs[*]:-} " == *" -l$l "* ]] || libs+=("-l$l")
    done
    for l in "${libs[@]}"; do
        [[ "$($cc -print-file-name=lib${l#-l}.a)" == /* ]] || echo "media.sh: note: no import library for $l"
    done
    local extra=()
    # windowscodecs: the tests reference IID_IMILBitmap* and the WIC metadata CLSIDs, which Wine's
    # own implib (dlls/windowscodecs/uuid.c, `#pragma makedep implib`) defines; build that object.
    if [[ $DLL == windowscodecs ]]; then
        local gc="$OUT/${DLL}_guids.c"
        {
            echo "#define WIN32_LEAN_AND_MEAN"
            echo "#include <windows.h>"
            echo "#include <ocidl.h>"
            echo "#include <propidl.h>"
            echo "#include <initguid.h>"
            echo "#include <wincodec.h>"
            echo "#include <wincodecsdk.h>"
            echo "#include \"$SRC/dlls/windowscodecs/uuid.c\""
        } > "$gc"
        extra+=("$gc")
    fi
    if [[ -f "$tdir/resource.rc" ]]; then
        local wr=x86_64-w64-mingw32-windres
        if command -v $wr >/dev/null && (cd "$tdir" && $wr -I"$tdir" -I"$SRC/include" -I"$GEN" -D__WINESRC__ \
                "$tdir/resource.rc" -O coff -o "$OUT/resource.o") > "$OUT/windres.log" 2>&1; then
            extra+=("$OUT/resource.o"); echo "media.sh: linked resource.rc"
        else
            echo "media.sh: note: resource.rc not compiled (see $OUT/windres.log); resource-based tests will fail"
        fi
    fi
    echo "media.sh: compiling ${#srcs[@]} test sources (${names[*]})"
    "$cc" "${flags[@]}" "${srcs[@]}" "$tl" "$ROOT/tests/wine-tests/wine_support.c" "${extra[@]}" -o "$EXE" \
        -Wl,--error-limit=0 "${libs[@]}" \
        || { echo "media.sh: build failed" >&2; exit 1; }
    echo "media.sh: built $EXE"
    # regdll.exe <module>: LoadLibrary + DllRegisterServer, what regsvr32 does, so the COM classes of
    # propsys/windowscodecs are in the registry as on an installed Windows (the tests CoCreateInstance them).
    local rc_="$OUT/regdll.c"
    cat > "$rc_" <<'REGEOF'
#include <windows.h>
static void out(const char *s) { DWORD n; WriteFile(GetStdHandle(STD_OUTPUT_HANDLE), s, lstrlenA(s), &n, NULL); }
void regdll_start(void)
{
    const char *p = GetCommandLineA();
    char hex[] = "0123456789abcdef", num[11];
    HRESULT hr = 0x80070002;
    HMODULE m;
    int i;
    if (*p == '"') { for (p++; *p && *p != '"'; p++) ; if (*p) p++; } else while (*p && *p != ' ') p++;
    while (*p == ' ') p++;
    m = LoadLibraryA(p);
    if (m)
    {
        HRESULT (WINAPI *reg)(void) = (void *)GetProcAddress(m, "DllRegisterServer");
        hr = reg ? reg() : 0x8007007f;
    }
    out("regdll: "); out(p); out(" DllRegisterServer=0x");
    for (i = 0; i < 8; i++) num[i] = hex[((unsigned)hr >> (28 - 4 * i)) & 15];
    num[8] = '\n'; num[9] = 0; out(num);
    ExitProcess(hr ? 1 : 0);
}
REGEOF
    "$cc" -O1 -w -nostdlib -Wl,-entry:regdll_start "$rc_" -o "$OUT/regdll.exe" -lkernel32 \
        || { echo "media.sh: regdll build failed" >&2; exit 1; }
}

baseline_of() {   # <unit> -> "<expect> <max>"
    [[ -f "$BASELINE" ]] || { echo "run 999999"; return; }
    awk -v u="$1" '$1 == u { print $2, $3; found = 1 } END { if (!found) print "run 999999" }' "$BASELINE"
}

do_run() {
    [[ -n "$HOST" && -n "$MACHINE" ]] || { echo "media.sh: run needs --host and --machine" >&2; exit 2; }
    [[ -f "$EXE" ]] || skip "$EXE missing (build step skipped or failed)"
    [[ -f "$MACHINE/Windows/builtin/ntdll.dll" ]] || skip "$MACHINE/Windows/builtin/ntdll.dll missing (Wine PE builtins)"
    [[ -f "$MACHINE/Windows/System32/c_1252.nls" ]] || skip "$MACHINE/Windows/System32/c_1252.nls missing (NLS data)"
    if [[ -z "$UNITS" ]]; then
        local mk="$SRC/dlls/$DLL/tests/Makefile.in"
        [[ -f "$mk" ]] || skip "$mk missing (run wine-pe/fetch-wine.sh)"
        UNITS="$(sed -n '/^SOURCES/,/^$/p' "$mk" | tr -d '\\' | tr ' \t' '\n\n' | grep '\.c$' | sed 's/\.c$//' | tr '\n' ' ')"
    fi
    mkdir -p "$MACHINE/guest-wine"
    cp -f "$EXE" "$MACHINE/guest-wine/${DLL}_test.exe"
    local wmachine="$MACHINE"
    if [[ -n "$EMULATOR" && "$wmachine" == /* ]]; then wmachine="Z:$wmachine"; fi
    wmachine="${wmachine//\//\\}"
    export WIN10XBOX_DEBUG="${WIN10XBOX_DEBUG_SPEC:--all}"
    local tsv="$OUT/${DLL}.tsv" total=0 bad=0
    local regs=""
    case "$DLL" in propsys) regs="propsys.dll" ;; windowscodecs) regs="propsys.dll windowscodecs.dll" ;; esac
    if [[ -n "$regs" && -f "$OUT/regdll.exe" ]]; then
        cp -f "$OUT/regdll.exe" "$MACHINE/guest-wine/regdll.exe"
        local r
        for r in $regs; do
            timeout -k 5 "$TIMEOUT" $EMULATOR "$HOST" --machine "$wmachine" "C:\\guest-wine\\regdll.exe" "$r" \
                < /dev/null 2>&1 | tr -d '\r' | sed 's/^/  /' | head -4
        done
    fi
    : > "$tsv"
    local re='([0-9]+) tests executed \(([0-9]+) marked as todo, ([0-9]+) as flaky, ([0-9]+) failures?\), ([0-9]+) skipped'
    local unit
    for unit in $UNITS; do
        local log="$OUT/${DLL}_$unit.log" t0 rc status=crashed ex=0 todo=0 fl=0 fails=0 sk=0 last=""
        t0=$(date +%s)
        timeout -k 5 "$TIMEOUT" $EMULATOR "$HOST" --machine "$wmachine" "C:\\guest-wine\\${DLL}_test.exe" "$unit" \
            < /dev/null > "$log" 2>&1
        rc=$?
        local secs=$(( $(date +%s) - t0 ))
        local summary; summary="$(grep -aE "^[0-9a-f]+:$unit:.*$re" "$log" | tail -1)"
        [[ -z "$summary" ]] && summary="$(grep -aE "$re" "$log" | tail -1)"
        if [[ $rc -eq 124 || $rc -eq 137 ]]; then
            status=timeout
        elif [[ -n "$summary" && "$summary" =~ $re ]]; then
            status=ok; ex=${BASH_REMATCH[1]}; todo=${BASH_REMATCH[2]}; fl=${BASH_REMATCH[3]}
            fails=${BASH_REMATCH[4]}; sk=${BASH_REMATCH[5]}
        fi
        if [[ $status != ok ]]; then
            last="$(grep -aoE '[A-Za-z0-9_]+\.c:[0-9]+:[^\r]*' "$log" | tail -1 | cut -c1-160)"
        fi
        # Executed counts survive a crash: Wine prints them only at the end, so a
        # crashed unit contributes 0 to the total.
        total=$(( total + ex ))
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$unit" "$status" "$ex" "$todo" "$fl" "$fails" "$sk" \
            "$rc" "$secs" "$last" >> "$tsv"
        echo "WINETEST $DLL:$unit status=$status executed=$ex todo=$todo flaky=$fl failures=$fails skipped=$sk exit=$rc time=${secs}s"
        [[ -n "$last" ]] && echo "  last test line: $last"
        grep -aE 'Test (failed|marked todo)|Unhandled exception|Test failed' "$log" | head -3 | cut -c1-200 | sed 's/^/  first: /'
        grep -a '^win10xbox: ' "$log" | head -3 | sed 's/^/  /'
        read -r expect max <<<"$(baseline_of "$unit")"
        if [[ $expect == run ]]; then
            if [[ $status != ok ]]; then
                echo "  REGRESSION: baseline is 'completes', now $status"; bad=1
            elif (( fails > max )); then
                echo "  REGRESSION: $fails failures, baseline allows $max"; bad=1
            elif (( fails < max )); then
                echo "  IMPROVED: $fails failures < baseline $max; lower $BASELINE"
            fi
        elif [[ $status == ok ]]; then
            echo "  IMPROVED: now completes ($ex executed, $fails failures), baseline is '$expect'; update $BASELINE"
        else
            echo "  XFAIL: $status as recorded"
        fi
    done
    echo "WINETEST $DLL total executed=$total"
    # A suite whose baseline records only crash/timeout units executes no counted
    # assertion by definition; every other suite must execute at least one.
    if (( total < 1 )) && grep -qE '^[^#[:space:]]+[[:space:]]+run[[:space:]]' "$BASELINE" 2>/dev/null; then
        echo "FAIL: no assertion executed in any unit"; exit 1
    fi
    if (( total < 1 )) && [[ ! -f "$BASELINE" ]]; then echo "FAIL: no assertion executed in any unit"; exit 1; fi
    (( bad == 0 )) || { echo "FAIL: $DLL conformance below baseline (logs in $OUT)"; exit 1; }
    echo "PASS (baseline holds)"
}

case "$MODE" in
    build) do_build ;;
    run) do_run ;;
    all) do_build; do_run ;;
    *) sed -n '2,/^set -uo/p' "${BASH_SOURCE[0]}" | sed '$d' | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
