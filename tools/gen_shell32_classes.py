#!/usr/bin/env python3
"""Generate core/registry/shell32_classes.inc from wine-pe/wine-src/dlls/shell32/shell32_classes.idl.

Each coclass becomes one row {clsid, name, threading model, progid, version-independent progid}: what widl's
registration script (shell32's DllRegisterServer) writes. Usage: gen_shell32_classes.py [idl] [out]."""
import re, sys
idl = sys.argv[1] if len(sys.argv) > 1 else "wine-pe/wine-src/dlls/shell32/shell32_classes.idl"
out = sys.argv[2] if len(sys.argv) > 2 else "core/registry/shell32_classes.inc"
text = open(idl).read()
rows = []
for m in re.finditer(r"\[(.*?)\]\s*coclass\s+(\w+)", text, re.S):
    attrs, name = m.group(1), m.group(2)
    u = re.search(r"uuid\(([0-9a-fA-F-]{36})\)", attrs)
    if not u: continue
    hs = re.search(r'helpstring\("([^"]*)"\)', attrs)
    th = re.search(r"threading\((\w+)\)", attrs)
    pi = re.search(r'progid\("([^"]*)"\)', attrs)
    vi = re.search(r'vi_progid\("([^"]*)"\)', attrs)
    tm = {"apartment": "Apartment", "both": "Both", "free": "Free", "neutral": "Neutral"}.get(th.group(1) if th else "", "")
    rows.append(("{%s}" % u.group(1).upper(), hs.group(1) if hs else name, tm,
                 pi.group(1) if pi else "", vi.group(1) if vi else ""))
with open(out, "w") as f:
    f.write("// Generated by tools/gen_shell32_classes.py from shell32_classes.idl; do not edit.\n")
    for r in rows:
        f.write("{" + ", ".join('L"%s"' % x for x in r) + "},\n")
print(len(rows), "classes")
