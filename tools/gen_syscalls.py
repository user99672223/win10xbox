#!/usr/bin/env python3
"""Generate the dispatcher syscall table from Wine's ntsyscalls.h.

Wine's dlls/ntdll/ntsyscalls.h carries the real Windows 10 x64 syscall numbers
in its ``ALL_SYSCALLS`` macro (the _WIN64 arm), as
``SYSCALL_ENTRY( 0x0018, NtAllocateVirtualMemory, 48 )`` where the third field
is argument *bytes* (8 per argument on x64). We emit, in id order:

    SYSCALL(0x0018, NtAllocateVirtualMemory, 6)

(id, name, argument COUNT). The dispatcher #includes this file and combines it
with core/dispatch/syscall_policy.inc to build its table. Run via CMake or:

    tools/gen_syscalls.py wine-pe/wine-src/dlls/ntdll/ntsyscalls.h \
        core/dispatch/syscall_table.gen.inc \
        [core/dispatch/syscall_policy.inc docs/SYSCALLS.md]

With the optional 3rd/4th arguments it also reads the hand-maintained policy
file and writes docs/SYSCALLS.md (per-syscall passthrough/translate/emulate/
todo status). This is mechanical transcription of public syscall numbers; it
adds no Wine code to our tree, so the output stays MIT.
"""
import re
import sys
import datetime

ENTRY = re.compile(
    r"SYSCALL_ENTRY\w*\(\s*(0x[0-9a-fA-F]+)\s*,\s*(\w+)\s*,\s*(\d+)\s*\)")


def extract_win64_block(text: str) -> str:
    # The 64-bit table is: #ifdef _WIN64 \n #define ALL_SYSCALLS ... up to #else
    m = re.search(r"#ifdef\s+_WIN64\s*\n#define\s+ALL_SYSCALLS\s+\\(.*?)\n#else",
                  text, re.S)
    if not m:
        raise SystemExit("could not find the _WIN64 ALL_SYSCALLS block")
    return m.group(1)


def parse(block: str):
    out = []
    for id_hex, name, nbytes in ENTRY.findall(block):
        nid = int(id_hex, 16)
        nargs = int(nbytes) // 8
        out.append((nid, name, nargs))
    out.sort(key=lambda e: e[0])
    # sanity: ids must be unique
    seen = set()
    for nid, name, _ in out:
        if nid in seen:
            raise SystemExit(f"duplicate syscall id {nid:#06x} ({name})")
        seen.add(nid)
    return out


POLICY_RE = re.compile(r'POLICY\(\s*(\w+)\s*,\s*(\w+)\s*,\s*"([^"]*)"\s*\)')


def parse_policy(path):
    pol = {}
    with open(path, "r", encoding="utf-8") as f:
        for name, policy, note in POLICY_RE.findall(f.read()):
            pol[name] = (policy, note)
    return pol


def write_syscalls_md(entries, policy, dst):
    counts = {"PassThrough": 0, "Translate": 0, "Emulate": 0, "Todo": 0}
    rows = []
    for nid, name, nargs in entries:
        pol, note = policy.get(name, ("Todo", ""))
        counts[pol] = counts.get(pol, 0) + 1
        rows.append((nid, name, nargs, pol, note))
    lines = [
        "# Syscall status",
        "",
        "Generated by `tools/gen_syscalls.py` from Wine's `ntsyscalls.h` (the real",
        "Windows 10 x64 / 22H2 NT syscall numbers) and the hand-maintained policy",
        "`core/dispatch/syscall_policy.inc`. Do not edit by hand.",
        "",
        f"{len(entries)} syscalls. "
        f"passthrough {counts['PassThrough']}, translate {counts['Translate']}, "
        f"emulate {counts['Emulate']}, todo {counts['Todo']}. "
        f"Generated {datetime.date.today().isoformat()}.",
        "",
        "Policy: **PassThrough** calls the host ntdll export by name; **Translate**",
        "rewrites arguments (paths, handles, timeouts) then passes through;",
        "**Emulate** is a user-mode implementation that never touches the host",
        "resource; **Todo** traces loudly and returns STATUS_NOT_IMPLEMENTED.",
        "",
        "| id | syscall | args | policy | note |",
        "|----|---------|------|--------|------|",
    ]
    for nid, name, nargs, pol, note in rows:
        lines.append(f"| 0x{nid:04x} | {name} | {nargs} | {pol} | {note} |")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"gen_syscalls: SYSCALLS.md -> {dst} "
          f"(pt {counts['PassThrough']}, tr {counts['Translate']}, "
          f"em {counts['Emulate']}, todo {counts['Todo']})")


def main(argv):
    if len(argv) not in (3, 5):
        raise SystemExit(f"usage: {argv[0]} <ntsyscalls.h> <out.inc> [<policy.inc> <out.md>]")
    src, dst = argv[1], argv[2]
    with open(src, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()
    entries = parse(extract_win64_block(text))
    lines = [
        "// GENERATED by tools/gen_syscalls.py from Wine's ntsyscalls.h.",
        "// Do not edit. Windows 10 x64 (22H2) NT syscall ids. id, name, argcount.",
        f"// {len(entries)} entries, generated {datetime.date.today().isoformat()}.",
        "// Policy per syscall is in core/dispatch/syscall_policy.inc.",
        "#ifndef SYSCALL",
        "#error \"define SYSCALL(id, name, nargs) before including this file\"",
        "#endif",
    ]
    for nid, name, nargs in entries:
        lines.append(f"SYSCALL(0x{nid:04x}, {name}, {nargs})")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"gen_syscalls: {len(entries)} syscalls -> {dst}")
    if len(argv) == 5:
        policy = parse_policy(argv[3])
        write_syscalls_md(entries, policy, argv[4])


if __name__ == "__main__":
    main(sys.argv)
